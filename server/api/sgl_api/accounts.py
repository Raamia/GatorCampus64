"""Local account lifecycle. Provider accounts are never changed by this module."""
import hashlib
import time
import uuid

from psycopg.types.json import Jsonb
from . import runs

from .auth import AuthError


def subject_hash(sub):
    return hashlib.sha256(('sgl-deleted-account:' + sub).encode()).hexdigest()


def lock(c):
    c.execute("SELECT pg_advisory_xact_lock(hashtext('sgl_accounts'))")


def issued_at(claims):
    try:
        value = claims.get('iat')
        if isinstance(value, bool):
            raise ValueError()
        return int(value)
    except (TypeError, ValueError, OverflowError):
        raise AuthError(401, 'invalid token issue time')


def require_active(c, sub, claims=None):
    row = c.execute('SELECT deleted_before, reactivated FROM deleted_accounts WHERE subject_hash = %s',
                    (subject_hash(sub),)).fetchone()
    if row:
        if not row['reactivated']:
            raise AuthError(403, 'Gator account deleted; explicitly register again after signing in')
        if claims is not None and issued_at(claims) <= row['deleted_before']:
            raise AuthError(401, 'sign in again; this token predates account deletion')


def normalize_event(event):
    """Never retain identities of spectators attached to a run by older bridges."""
    nested = event.get('payload')
    fields = {**nested, **event} if isinstance(nested, dict) else event
    if fields.get('t') != 'run':
        return event
    participants = {str(g) for g in runs.parse(fields)['gis'] if g is not None}
    def clean(f):
        f = dict(f)
        if isinstance(f.get('identities'), dict):
            f['identities'] = {k: v for k, v in f['identities'].items() if k in participants}
        # A run belongs to its participant list, not the player who forwarded it.
        f.pop('identity', None)
        f.pop('connection_id', None)
        return f
    result = clean(event)
    if isinstance(nested, dict):
        result['payload'] = clean(nested)
    return result


def erased_event(c, fields, bridge_sub):
    fields = normalize_event(fields)
    try:
        key = uuid.UUID(str(fields.get('event_id')))
    except ValueError:
        key = None
    if key and c.execute('SELECT 1 FROM erased_events WHERE bridge_sub = %s AND event_key = %s',
                         (bridge_sub, key)).fetchone():
        return True
    identities = fields.get('identities')
    values = list(identities.values()) if isinstance(identities, dict) else []
    values.append(fields.get('identity'))
    ids = [v['link_id'] for v in values if isinstance(v, dict) and type(v.get('link_id')) is int
           and 0 < v['link_id'] < 2**63]
    if ids and c.execute('SELECT 1 FROM erased_links WHERE link_id = ANY(%s)', (ids,)).fetchone():
        return True
    # Per-connection metadata is generated by the updated bridge, including unlinked leave events.
    try:
        session, connection = uuid.UUID(str(fields.get('session_id'))), uuid.UUID(str(fields.get('connection_id')))
    except ValueError:
        return False
    return bool(c.execute('SELECT 1 FROM erased_links WHERE session_id = %s AND connection_id = %s',
                          (session, connection)).fetchone())


def delete_account(c, sub, event_fields, claims):
    # Coordinate with uploads, login publication and run ingestion before taking slot/character locks.
    c.execute("SELECT pg_advisory_xact_lock(hashtext('sgl_create'))")
    lock(c)
    require_active(c, sub, claims)
    c.execute("SELECT pg_advisory_xact_lock(hashtext('sgl_slots'))")
    c.execute('INSERT INTO deleted_accounts (subject_hash, deleted_before) VALUES (%s, %s) '
              'ON CONFLICT (subject_hash) DO UPDATE SET deleted_before = EXCLUDED.deleted_before, reactivated = false',
              (subject_hash(sub), int(time.time())))
    links = c.execute('SELECT * FROM links WHERE sub = %s', (sub,)).fetchall()
    c.execute('INSERT INTO erased_links (link_id, session_id, connection_id) '
              'SELECT id, session_id, connection_id FROM links WHERE sub = %s ON CONFLICT DO NOTHING', (sub,))
    affected = c.execute('SELECT id, uid, event_id FROM runs WHERE %s = ANY(subs)', (sub,)).fetchall()
    event_ids = {r['event_id'] for r in affected if r['event_id'] is not None}
    # Older non-run events lack connection IDs: remove only records matching a known session/player alias.
    sessions = [link['session_id'] for link in links if link['session_id']]
    for event in c.execute('SELECT id, bridge_sub, payload FROM events WHERE session_id = ANY(%s)', (sessions,)):
        f = event_fields(event['payload'])
        matched = any(str(link['session_id']) == str(f.get('session_id'))
                      and link['bridge_sub'] == event['bridge_sub']
                      and link['gi'] == f.get('gi') and link['coopdx_name'] == f.get('name') for link in links)
        if (matched and f.get('t') != 'run') or erased_event(c, f, event['bridge_sub']):
            event_ids.add(event['id'])
        else:
            cleaned = normalize_event(event['payload'])
            if cleaned != event['payload']:
                c.execute('UPDATE events SET payload = %s WHERE id = %s', (Jsonb(cleaned), event['id']))
    # Invalid/unranked runs can still contain the account's captured link references.
    affected = c.execute('SELECT id, uid FROM runs WHERE %s = ANY(subs) OR event_id = ANY(%s)',
                         (sub, list(event_ids))).fetchall()
    for run in affected:
        c.execute('INSERT INTO run_erases (uid) VALUES (%s) ON CONFLICT DO NOTHING', (run['uid'],))
    c.execute('DELETE FROM runs WHERE id = ANY(%s)', ([run['id'] for run in affected],))
    c.execute('INSERT INTO erased_events (bridge_sub, event_key) '
              'SELECT bridge_sub, event_key FROM events WHERE id = ANY(%s) AND event_key IS NOT NULL '
              'AND bridge_sub IS NOT NULL ON CONFLICT DO NOTHING', (list(event_ids),))
    c.execute('DELETE FROM events WHERE id = ANY(%s)', (list(event_ids),))
    for char in c.execute('SELECT id FROM characters WHERE owner_sub = %s ORDER BY id FOR UPDATE', (sub,)).fetchall():
        c.execute('SELECT sgl_release_slot(%s)', (char['id'],))
    c.execute('DELETE FROM users WHERE sub = %s', (sub,))  # cascades enqueue durable object cleanup
    return len(affected)
