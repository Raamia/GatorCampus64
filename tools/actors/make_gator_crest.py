"""Generate a Gator Crest that replaces SM64's collectible star model.

DynOS matches the vanilla `star_geo` layout symbol, so the familiar star
collection behavior, saved star ids, and course unlocks remain intact.

Usage: python3 -I tools/actors/make_gator_crest.py [--out DIR]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_gators as G  # noqa: E402

ROOT = G.ROOT
OUT = os.path.join(ROOT, "mods", "sgl64", "actors", "star")
NAME = "sgl_crest"

G.COLORS.update({
    "crest_gold": (255, 204, 72),
    "crest_gold_shadow": (171, 94, 25),
    "crest_orange": (247, 105, 31),
    "crest_navy": (12, 31, 73),
    "crest_blue": (31, 100, 181),
    "crest_green": (0, 119, 78),
    "crest_light": (105, 190, 114),
    "crest_dark": (0, 57, 43),
    "crest_cream": (255, 246, 207),
    "crest_eye": (18, 23, 25),
})

# Shield outline, ordered counter-clockwise when viewed from the front (+Z).
SHIELD = [(0, 0), (29, 17), (39, 37), (42, 61), (35, 79), (21, 89),
          (-21, 89), (-35, 79), (-42, 61), (-39, 37), (-29, 17)]
INNER = [(0, 10), (23, 24), (32, 41), (34, 60), (28, 73), (17, 81),
         (-17, 81), (-28, 73), (-34, 60), (-32, 41), (-23, 24)]
INLAY = [(0, 18), (17, 29), (25, 43), (26, 58), (21, 68), (13, 75),
         (-13, 75), (-21, 68), (-26, 58), (-25, 43), (-17, 29)]


def _center(poly):
    return (sum(p[0] for p in poly) / len(poly), sum(p[1] for p in poly) / len(poly))


def _face(mesh, mat, poly, z, side):
    """Triangulate a convex enamel panel with its normal facing out from either side."""
    cx, cy = _center(poly)
    center = (cx, cy, side * z)
    points = [(x, y, side * z) for x, y in poly]
    for i, a in enumerate(points):
        b = points[(i + 1) % len(points)]
        mesh.tri(mat, center, a, b) if side > 0 else mesh.tri(mat, center, b, a)


def _prism(mesh, mat, poly, front_z, back_z):
    """Extrude a convex polygon and close its sides."""
    cx, cy = _center(poly)
    front = [(x, y, front_z) for x, y in poly]
    back = [(x, y, back_z) for x, y in poly]
    front_center, back_center = (cx, cy, front_z), (cx, cy, back_z)
    for i in range(len(poly)):
        j = (i + 1) % len(poly)
        mesh.tri(mat, front_center, front[i], front[j])
        mesh.tri(mat, back_center, back[j], back[i])
        mesh.quad(mat, front[i], back[i], back[j], front[j], (cx, cy, (front_z + back_z) / 2))


def _gator_profile(mesh, side):
    """Build a raised, readable alligator profile on both faces of the crest."""
    z = side * 12.0
    # A single connected silhouette: rounded skull, long upper snout and a clear lower jaw.
    mesh.ball("crest_dark", (-8, 53, z), (18, 13, 3.2), seg=10, rings=5)
    mesh.ball("crest_green", (-8, 55, z + side * 1.5), (16, 10.5, 3.1), seg=10, rings=5)
    mesh.ball("crest_light", (11, 51, z + side * 1.0), (18, 4.8, 3.0), seg=10, rings=4)
    mesh.ball("crest_green", (11, 42.5, z + side * 1.5), (16, 3.5, 2.7), seg=10, rings=4)
    # Keep the mouth narrow and continuous; teeth point down from the upper jaw.
    mesh.box("crest_dark", -2, 29, 46, 47, z + side * 3.1 - 0.7, z + side * 3.1 + 0.7)
    for x in (3, 10, 17, 24):
        p = [(x, 47.4, z + side * 3.8), (x + 2.4, 47.4, z + side * 3.8),
             (x + 1.2, 44.8, z + side * 3.8)]
        mesh.tri("crest_cream", p[0], p[1], p[2]) if side > 0 else mesh.tri("crest_cream", p[0], p[2], p[1])
    # A small nostril and tidy eye make the animal readable without breaking the shield silhouette.
    mesh.ball("crest_dark", (27, 54, z + side * 3.3), (1.4, 1.0, 0.9), seg=6, rings=3)
    mesh.ball("crest_gold", (-16, 63, z + side * 3.1), (4.2, 3.8, 2.0), seg=8, rings=4)
    mesh.ball("crest_cream", (-16, 63, z + side * 4.4), (2.3, 2.5, 1.4), seg=8, rings=4)
    mesh.ball("crest_eye", (-15, 63, z + side * 5.4), (1.0, 1.5, 0.8), seg=6, rings=3)


def build_mesh():
    mesh = G.Mesh()
    # A compact, beveled shield: gold edge, orange pinstripe, deep-blue enamel.
    _prism(mesh, "crest_gold_shadow", SHIELD, 7.0, -7.0)
    for side in (-1, 1):
        _face(mesh, "crest_gold", SHIELD, 7.15, side)
        _face(mesh, "crest_orange", INNER, 7.5, side)
        _face(mesh, "crest_navy", INLAY, 7.85, side)
        _gator_profile(mesh, side)
    return mesh


def build():
    mesh = build_mesh()
    vtx, dls, used = [], [], set()
    top = G.emit_mesh(NAME, mesh, "crest", vtx, dls, used)
    model = "// GENERATED by tools/actors/make_gator_crest.py. Do not edit; edit the script and re-run it.\n\n"
    model += "\n".join(G.materials(NAME, used)) + "\n" + "\n".join(vtx) + "\n" + "\n".join(dls)
    model = "\n".join(line.rstrip() for line in model.splitlines()) + "\n"
    geo = ("// GENERATED by tools/actors/make_gator_crest.py. Do not edit; edit the script and re-run it.\n\n"
           "// Replaces the vanilla star appearance while preserving bhvStar collection and saved star ids.\n"
           "const GeoLayout star_geo[] = {\n"
           "\tGEO_SHADOW(SHADOW_CIRCLE_4_VERTS, 0x96, 90),\n"
           "\tGEO_OPEN_NODE(),\n"
           "\t\tGEO_DISPLAY_LIST(LAYER_OPAQUE, %s),\n"
           "\tGEO_CLOSE_NODE(),\n"
           "\tGEO_END(),\n"
           "};\n") % top
    header = ["extern const GeoLayout star_geo[];"]
    for mat in sorted(used):
        header += ["extern Lights1 %s_%s_lights;" % (NAME, mat),
                   "extern Gfx mat_%s_%s[];" % (NAME, mat),
                   "extern Gfx mat_revert_%s_%s[];" % (NAME, mat)]
    header += ["extern " + chunk.split(" = ")[0] + ";" for chunk in vtx + dls]
    triangles = sum(len(tris) for tris in mesh.tris.values())
    return model, geo, "\n".join(header) + "\n", triangles, mesh


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=OUT, help="actor folder (default mods/sgl64/actors/star)")
    args = parser.parse_args(argv)
    model, geo, header, triangles, _ = build()
    os.makedirs(args.out, exist_ok=True)
    for filename, text in (("model.inc.c", model), ("geo.inc.c", geo), ("geo_header.h", header)):
        with open(os.path.join(args.out, filename), "w") as output:
            output.write(text)
    print("make_gator_crest: %d triangles -> %s (star_geo)" % (triangles, os.path.relpath(args.out, ROOT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
