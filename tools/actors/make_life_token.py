"""Generate the Gator extra-life medallion that replaces the vanilla 1-Up mushroom model.

The object keeps SM64's bhv1Up pickup behaviour (+1 life, then despawn), but DynOS substitutes this actor for
MODEL_1UP by matching the vanilla `mushroom_1up_geo` layout symbol. This keeps all existing map placements.

Usage: python3 -I tools/actors/make_life_token.py [--out DIR]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_gators as G  # noqa: E402

ROOT = G.ROOT
OUT = os.path.join(ROOT, "mods", "sgl64", "actors", "mushroom_1up")
NAME = "sgl_life"

G.COLORS.update({
    "coin_gold": (247, 190, 50),
    "coin_light": (255, 226, 112),
    "coin_shadow": (143, 83, 22),
    "badge_green": (0, 103, 71),
    "badge_dark": (0, 55, 42),
    "badge_light": (92, 171, 82),
    "eye_white": (250, 250, 245),
    "eye_black": (15, 20, 18),
    "tooth": (255, 248, 220),
})


def add_gator_face(mesh, side):
    """A raised, readable alligator profile on one face of the medallion."""
    z = side
    # Gator head looking right: long jaw and brow, with a separate bright upper snout.
    mesh.ball("badge_dark", (-4, 31, z * 9), (15, 10, 2.5), seg=10, rings=5)
    mesh.ball("badge_green", (8, 29, z * 10), (14, 6, 2.8), seg=10, rings=4)
    mesh.ball("badge_light", (6, 35, z * 10), (14, 5, 2.5), seg=10, rings=4)
    # Jaw line and a row of small teeth make the silhouette read as a gator at pickup scale.
    mesh.box("badge_dark", -11, 20, 25, 27, z * 12 - 1, z * 12 + 1)
    for x in (-5, 1, 7, 13):
        mesh.pyramid("tooth", [(x, 25, z * 13), (x + 2, 25, z * 13),
                                (x + 2, 28, z * 13), (x, 28, z * 13)], (x + 1, 25, z * 13))
    mesh.ball("eye_white", (-12, 39, z * 10), (4.0, 4.5, 2.5), seg=8, rings=4)
    mesh.ball("eye_black", (-11, 39, z * 12), (1.5, 2.5, 1.2), seg=6, rings=4)


def build_mesh():
    mesh = G.Mesh()
    # A coin-shaped, beveled medallion: gold rim, green enamel faces, raised gator on both sides.
    mesh.ball("coin_shadow", (0, 31, 0), (33, 33, 8), seg=14, rings=6)
    for side in (-1, 1):
        mesh.ball("coin_gold", (0, 31, side * 3.1), (31, 31, 5.3), seg=14, rings=6)
        mesh.ball("coin_light", (0, 31, side * 6.4), (27.5, 27.5, 2.1), seg=14, rings=6)
        mesh.ball("badge_green", (0, 31, side * 7.7), (24, 24, 1.9), seg=14, rings=6)
        add_gator_face(mesh, side)
    return mesh


def build():
    mesh = build_mesh()
    vtx, dls, used = [], [], set()
    top = G.emit_mesh(NAME, mesh, "medallion", vtx, dls, used)
    model = "// GENERATED by tools/actors/make_life_token.py. Do not edit; edit the script and re-run it.\n\n"
    model += "\n".join(G.materials(NAME, used)) + "\n" + "\n".join(vtx) + "\n" + "\n".join(dls)
    model = "\n".join(line.rstrip() for line in model.splitlines()) + "\n"
    geo = ("// GENERATED by tools/actors/make_life_token.py. Do not edit; edit the script and re-run it.\n\n"
           "// Replaces the vanilla 1-Up mushroom while retaining bhv1Up pickup behaviour.\n"
           "const GeoLayout mushroom_1up_geo[] = {\n"
           "\tGEO_SHADOW(SHADOW_CIRCLE_4_VERTS, 0x50, 70),\n"
           "\tGEO_OPEN_NODE(),\n"
           "\t\tGEO_DISPLAY_LIST(LAYER_OPAQUE, %s),\n"
           "\tGEO_CLOSE_NODE(),\n"
           "\tGEO_END(),\n"
           "};\n") % top
    header = ["extern const GeoLayout mushroom_1up_geo[];"]
    for mat in sorted(used):
        header += ["extern Lights1 %s_%s_lights;" % (NAME, mat),
                   "extern Gfx mat_%s_%s[];" % (NAME, mat),
                   "extern Gfx mat_revert_%s_%s[];" % (NAME, mat)]
    header += ["extern " + chunk.split(" = ")[0] + ";" for chunk in vtx + dls]
    triangles = sum(len(tris) for tris in mesh.tris.values())
    return model, geo, "\n".join(header) + "\n", triangles


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=OUT, help="actor folder (default mods/sgl64/actors/mushroom_1up)")
    args = parser.parse_args(argv)
    model, geo, header, triangles = build()
    os.makedirs(args.out, exist_ok=True)
    for filename, text in (("model.inc.c", model), ("geo.inc.c", geo), ("geo_header.h", header)):
        with open(os.path.join(args.out, filename), "w") as output:
            output.write(text)
    print("make_life_token: %d triangles -> %s (mushroom_1up_geo)" % (triangles, os.path.relpath(args.out, ROOT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
