"""Resolve semantic mascot anchors against built collision. Use --check for releases."""
from pathlib import Path
import json
import math
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from geometry import Collision
from navigation import ROOT, SLOTS, settings, excluded, supported, dependencies, fingerprint

ANCHORS = 'data/uf/npc_anchors.json'
OUT = 'mods/sgl64/sgl_ambient_data.lua'


def anchor_position(source, root=ROOT):
    text = (root / source['file']).read_text()
    if source.get('spawn'):
        hits = re.findall(r'MARIO_POS\(\s*(?:1|0x01),\s*-?\d+,\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\)', text)
        if not hits or len(set(hits)) != 1:
            raise ValueError('Missing or ambiguous hub spawn')
        x, y, z = map(int, hits[0])
        return [x, y + source.get('floor_offset', 0), z]
    found = []
    def visit(value):
        if isinstance(value, dict):
            if value.get('name') == source['point'] and isinstance(value.get('game'), list):
                found.append(value['game'])
            for child in value.values():
                visit(child)
        elif isinstance(value, list):
            for child in value:
                visit(child)
    visit(json.loads(text))
    if len(found) != 1 or len(found[0]) != 3:
        raise ValueError(f"Missing or ambiguous anchor: {source}")
    return found[0]


def resolve(col, spec, preferred, objects, config, slot):
    px, py, pz = preferred
    tolerance = spec['height_tolerance']
    radius = spec['radius']
    reach = max(radius + 60, 70)
    def safe(x, z):
        y = supported(col, x, z, py-tolerance, py+tolerance, 40, 260)
        if y is None or excluded(config, slot, spec['area'], x, y, z, reach, 260):
            return None
        if any(abs(oy-y) < 300 and math.hypot(ox-x, oz-z) < radius+120 for ox, oy, oz in objects):
            return None
        # Preserve a clear, nearly level stroll disk. Sloping terrain can host
        # a standing mascot; changing its authored stroll radius is deliberate.
        for dx in range(-reach, reach+1, 40):
            for dz in range(-reach, reach+1, 40):
                if dx*dx+dz*dz > reach*reach:
                    continue
                f = col.floor(x+dx, y+4-78, z+dz)
                if f is None or abs(f[0]-y) > 4:
                    return None
        if col.body_blocked(x, z, y+15, y+260, reach):
            return None
        return round(y)
    limit = spec['search_radius']
    offsets = [(x, z) for x in range(-limit, limit+1, 50)
               for z in range(-limit, limit+1, 50) if x*x+z*z <= limit*limit]
    offsets = sorted(set(offsets + [(0, 0)]), key=lambda p: (p[0]**2+p[1]**2, p))
    for dx, dz in offsets:
        y = safe(px+dx, pz+dz)
        if y is not None:
            return round(px+dx), y, round(pz+dz)
    raise ValueError(f"No safe required mascot placement near {spec['anchor']}")


def generate(root=ROOT):
    config = settings(root)
    definition = json.loads((root / ANCHORS).read_text())
    if definition['schema'] != 1:
        raise ValueError('Unsupported anchor schema')
    paths = [ANCHORS, 'tools/npcs/placements.py']
    cache, rows = {}, []
    for name, spec in definition['spots'].items():
        slot, area = SLOTS[spec['level']], spec['area']
        paths += dependencies(slot, area) + [spec['anchor']['file']]
        key = (slot, area)
        if key not in cache:
            base = root / f'mods/sgl64/levels/{slot}'
            block = re.search(rf'\bAREA\({area},.*?END_AREA\(\)', (base/'script.c').read_text(), re.S).group()
            objects = [tuple(map(int, xyz)) for xyz in re.findall(
                r'OBJECT(?:_WITH_ACTS)?\(\s*\w+,\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)', block)]
            cache[key] = Collision(base/f'area_{area}/collision.inc.c'), objects
        preferred = [a+b for a, b in zip(anchor_position(spec['anchor'], root), spec['offset'])]
        x, y, z = resolve(cache[key][0], spec, preferred, cache[key][1], config, slot)
        rows.append(f'    {name} = {{ level = {spec["level"]}, area = {area}, x = {x}, y = {y}, z = {z}, '
                    f'yaw = {spec["yaw"]}, radius = {spec["radius"]},\n'
                    f'        label = {json.dumps(spec["label"])} }},')
    lines = ['-- GENERATED by tools/npcs/placements.py; edit named anchors, not coordinates.',
             '-- Source SHA256: '+fingerprint(paths, root), 'SGL_NPC_SPOTS = {', *rows, '}',
             'SGL_NPC_EXCLUSIONS = {']
    levels = {v:k for k,v in SLOTS.items()}
    for box in config['exclusions']:
        coords = ', '.join(str(v) for v in box['min']+box['max'])
        lines.append(f'    {{ level = {levels[box["slot"]]}, area = {box["area"]}, bounds = {{ {coords} }} }},')
    lines += ['}', '']
    return '\n'.join(lines)


def main():
    output = generate()
    path = ROOT / OUT
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != output:
            raise SystemExit('NPC placements stale; run python3 -I tools/npcs/placements.py')
        print('NPC placements: current and collision-validated')
    else:
        path.write_text(output)
        print('Generated map-derived mascot placements')


if __name__ == '__main__':
    main()
