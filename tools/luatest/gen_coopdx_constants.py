"""Extract sm64coopdx's Lua constants prelude (gSmluaConstants in src/pc/lua/smlua_constants_autogen.c)
into tools/luatest/coopdx_constants_v151.lua, so the offline tests run the mods against the real
v1.5.1 constant values (LEVEL_BOB, ACT_*, SOUND_*, E_MODEL_*, id_bhv*, ...).

Usage: python3 gen_coopdx_constants.py <smlua_constants_autogen.c of tag v1.5.1> > coopdx_constants_v151.lua
"""
import ast
import sys

text = open(sys.argv[1]).read()
start = text.index("gSmluaConstants[]")
body = text[text.index("=", start) + 1:text.index("\n;", start)]
out = []
for line in body.splitlines():
    line = line.strip()
    if line.startswith('"') and line.endswith('"'):
        out.append(ast.literal_eval(line))
print("-- GENERATED by tools/luatest/gen_coopdx_constants.py from sm64coopdx v1.5.1")
print("-- src/pc/lua/smlua_constants_autogen.c (gSmluaConstants). Do not edit.")
sys.stdout.write("".join(out))
