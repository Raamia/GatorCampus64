"""Generate tools/luatest/coopdx_api_v151.lua: every Lua function sm64coopdx v1.5.1 binds, with the
argument counts its C binding accepts (from the 'top != N' / 'top < A || top > B' /
smlua_functions_valid_param_* checks). check_api.lua uses it to catch misspelt APIs and wrong
argument counts in mods/sgl64/*.lua without running the game.

Usage: python3 gen_coopdx_api.py <dir with the v1.5.1 sources> > coopdx_api_v151.lua
The directory needs these files from github.com/coop-deluxe/sm64coopdx at tag v1.5.1 (any of the
two naming styles: flat 'src_pc_lua_smlua_functions.c' or plain 'smlua_functions.c'):
  src/pc/lua/smlua_functions_autogen.c, smlua_functions.c, smlua_hooks.c, smlua_cobject.c
e.g. gh api -H "Accept: application/vnd.github.raw" \
       "repos/coop-deluxe/sm64coopdx/contents/src/pc/lua/smlua_functions.c?ref=v1.5.1" > smlua_functions.c
"""
import os
import re
import sys

src = sys.argv[1]
names = ["smlua_functions_autogen.c", "smlua_functions.c", "smlua_hooks.c", "smlua_cobject.c"]
bind_re = re.compile(r'smlua_bind_function\(L,\s*"([A-Za-z_0-9]+)",\s*([A-Za-z_0-9]+)\)')
func_re = re.compile(r'^(?:static\s+)?int\s+([A-Za-z_0-9]+)\(lua_State\s*\*\s*L\)\s*\{', re.M)

bodies, binds = {}, {}
for n in names:
    path = None
    for cand in (n, "src_pc_lua_" + n):
        if os.path.exists(os.path.join(src, cand)):
            path = os.path.join(src, cand)
    if path is None:
        sys.exit("missing " + n)
    text = open(path).read()
    for m in bind_re.finditer(text):
        binds[m.group(1)] = m.group(2)
    starts = [(m.start(), m.group(1)) for m in func_re.finditer(text)]
    for i, (pos, fname) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else len(text)
        bodies[fname] = text[pos:end][:1500]


def counts(body):
    if body is None:
        return None
    m = re.search(r'valid_param_count\(L,\s*(\d+)\)', body)
    if m:
        return int(m.group(1)), int(m.group(1))
    m = re.search(r'valid_param_range\(L,\s*(\d+),\s*(\d+)\)', body)
    if m:
        return int(m.group(1)), int(m.group(2))
    m = re.search(r'if\s*\(\s*top\s*<\s*(\d+)\s*\|\|\s*top\s*>\s*(\d+)\s*\)', body)
    if m:
        return int(m.group(1)), int(m.group(2))
    m = re.search(r'if\s*\(\s*top\s*!=\s*(\d+)\s*&&\s*top\s*!=\s*(\d+)\s*\)', body)
    if m:
        return min(int(m.group(1)), int(m.group(2))), max(int(m.group(1)), int(m.group(2)))
    m = re.search(r'if\s*\(\s*top\s*!=\s*(\d+)\s*\)', body)
    if m:
        return int(m.group(1)), int(m.group(1))
    return None


print("-- GENERATED by tools/luatest/gen_coopdx_api.py from sm64coopdx v1.5.1 (src/pc/lua). Do not edit.")
print("-- name = { min args, max args } (-1, -1: not determined; only the name is checked)")
print("return {")
for name in sorted(binds):
    c = counts(bodies.get(binds[name]))
    lo, hi = c if c else (-1, -1)
    print('    ["%s"] = { %d, %d },' % (name, lo, hi))
print("}")
