"""Extract the fields of a few coopdx structs from docs/lua/structs.md (tag v1.5.1) into
tools/luatest/coopdx_structs_v151.lua. The simulation (sim.lua) makes Object / MarioState /
NetworkPlayer / Controller tables strict with it: touching a field the real struct does not have
fails the test (coopdx logs an error and ignores it in game), and writing a read-only one fails too.

Usage: python3 gen_coopdx_structs.py <structs.md of tag v1.5.1> > coopdx_structs_v151.lua
"""
import re
import sys

text = open(sys.argv[1]).read()
print("-- GENERATED by tools/luatest/gen_coopdx_structs.py from sm64coopdx v1.5.1 docs/lua/structs.md. Do not edit.")
print("-- struct = { field = true (writable) | false (read-only) }")
print("return {")
for struct in ("Object", "MarioState", "NetworkPlayer", "Controller"):
    m = re.search(r"^## \[" + struct + r"\]\(#" + struct + r"\)\n(.*?)(?=^## \[)", text, re.S | re.M)
    print("    %s = {" % struct)
    for line in m.group(1).splitlines():
        f = re.match(r"^\| ([A-Za-z_][A-Za-z_0-9]*) \| (.*?) \| (.*?) \|$", line)
        if f and f.group(1) != "Field":
            print('        ["%s"] = %s,' % (f.group(1), "false" if "read-only" in f.group(3) else "true"))
    print("    },")
print("}")
