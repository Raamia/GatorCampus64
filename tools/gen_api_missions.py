#!/usr/bin/env python3
"""Generate server/api/sgl_api/missions.py (the API's mission table, docs/web_platform_spec.md §10)
from the `sgl_mission_register({...})` definitions in mods/sgl64/*_missions.lua.

    python3 tools/gen_api_missions.py           # rewrite the module
    python3 tools/gen_api_missions.py --check   # exit 1 if the module is out of date (CI / tests)

Each mission gets a FLOOR: the minimum plausible host-measured time, in frames (30 fps). A `run`
event faster than its mission's floor is stored but never ranked. Floors are deliberately loose:
they catch a broken or forged clock, not a great run. Derivation, first rule that applies:

  1. the mission's race spec has a `gold` time (seconds): floor = gold / 2. The gold time is the
     designers' "very good" mark (Stadium Stair Sprint: gold 45 s, the ideal line is ~31-38 s),
     so half of it is below any real run.
  2. it has a `par` but no `gold`: floor = par / 3.
  3. a per-mission constant from FLOOR_SECS below (documented there).
  4. otherwise DEFAULT_FLOOR_SECS (10 s): every mission is a multi-step task on a real-scale campus
     (a 66 m climb, 8 tokens, two-player switch puzzles); none can be done in 10 s from the moment
     the round goes active.
"""

from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = sorted((ROOT / "mods/sgl64").glob("*_missions.lua"))
TARGET = ROOT / "server/api/sgl_api/missions.py"
FPS = 30
DEFAULT_FLOOR_SECS = 10
# Missions without par/gold whose own rules put a hard lower bound on the time:
FLOOR_SECS = {
    # BAT CENSUS: success needs 600 + 300 per extra player bats (kind_census: 6.5 bats/s per staffed
    # post, +3 per extra counter at the same post, 3 posts). Fastest cases: 2 players at two posts
    # 900 / 13 = 69 s; 3 players at three posts 1200 / 19.5 = 61.5 s; 4 players 1500 / 22.5 = 67 s.
    "lake_bat_census": 60,
}

REGISTER = re.compile(r"sgl_mission_register\s*\(\s*\{(.*?)^\}\)", re.MULTILINE | re.DOTALL)


def lua_string(block: str, field: str) -> str | None:
    m = re.search(rf'^\s*{field}\s*=\s*"((?:[^"\\]|\\.)*)"\s*,?', block, re.MULTILINE)
    return m.group(1) if m else None


def lua_number(block: str, field: str) -> float | None:
    m = re.search(rf"^\s*{field}\s*=\s*(\d+(?:\.\d+)?)\s*,", block, re.MULTILINE)
    return float(m.group(1)) if m else None


def missions() -> list[dict]:
    out: list[dict] = []
    seen: set[str] = set()
    for path in SOURCES:
        for m in REGISTER.finditer(path.read_text(encoding="utf-8")):
            block = m.group(1)
            mid = lua_string(block, "id")
            if mid is None:
                continue
            title = lua_string(block, "title")
            if title is None:
                raise ValueError(f"{path.name}: {mid} has no title")
            if mid in seen:
                raise ValueError(f"duplicate mission id {mid}")
            seen.add(mid)
            par, gold = lua_number(block, "par"), lua_number(block, "gold")
            if gold is not None:
                secs, rule = gold / 2, "gold/2"
            elif par is not None:
                secs, rule = par / 3, "par/3"
            elif mid in FLOOR_SECS:
                secs, rule = FLOOR_SECS[mid], "constant"
            else:
                secs, rule = DEFAULT_FLOOR_SECS, "default"
            out.append({"id": mid, "title": title, "source": path.name,
                        "par": int(par) if par is not None else None,
                        "gold": int(gold) if gold is not None else None,
                        "floor_frames": math.ceil(secs * FPS), "floor_rule": rule})
    unknown = set(FLOOR_SECS) - seen
    if unknown:
        raise ValueError(f"FLOOR_SECS names unknown missions: {sorted(unknown)}")
    return out


def render() -> str:
    lines = [
        '"""Mission table for verified leaderboards (docs/web_platform_spec.md §10).',
        "",
        "GENERATED by tools/gen_api_missions.py from mods/sgl64/*_missions.lua: do not edit by hand.",
        "Regenerate after adding or changing a mission (tests/test_missions.py checks it is in sync).",
        "floor_frames: minimum plausible host-measured time at 30 fps; the derivation (floor_rule) is",
        "documented in the generator's docstring.",
        '"""',
        "",
        "FPS = 30",
        "",
        "MISSIONS: dict[str, dict] = {",
    ]
    for m in missions():
        lines.append(f"    {m['id']!r}: {{\"title\": {m['title']!r}, \"par\": {m['par']!r}, \"gold\": {m['gold']!r}, "
                     f"\"floor_frames\": {m['floor_frames']}, \"floor_rule\": {m['floor_rule']!r}, "
                     f"\"source\": {m['source']!r}}},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the generated module is out of date")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run python3 tools/gen_api_missions.py", file=sys.stderr)
            return 1
        print(f"{TARGET.relative_to(ROOT)}: in sync ({len(missions())} missions)")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(missions())} missions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
